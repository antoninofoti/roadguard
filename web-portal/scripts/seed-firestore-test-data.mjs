#!/usr/bin/env node

/**
 * Seed Firestore emulator with realistic test road damage reports.
 *
 * Creates diverse road damage reports in Rome for dashboard testing.
 * Records follow the Report schema used by Android + web portal.
 *
 * Usage:
 *   node scripts/seed-firestore-test-data.mjs
 *   node scripts/seed-firestore-test-data.mjs --count 24
 */

import { initializeApp } from "firebase/app";
import {
  connectAuthEmulator,
  createUserWithEmailAndPassword,
  getAuth,
  signInWithEmailAndPassword,
} from "firebase/auth";
import {
  connectFirestoreEmulator,
  initializeFirestore,
  collection,
  addDoc,
  GeoPoint,
} from "firebase/firestore";

// Firebase config (same as portal's emulator config)
const firebaseConfig = {
  apiKey: "demo-api-key",
  authDomain: "roadguard-demo.firebaseapp.com",
  projectId: "roadguard-demo",
  storageBucket: "roadguard-demo.appspot.com",
  messagingSenderId: "000000000000",
  appId: "1:000000000000:web:0000000000000000",
};

// Initialize Firebase and Firestore (emulator mode)
const app = initializeApp(firebaseConfig);
const auth = getAuth(app);
connectAuthEmulator(auth, "http://127.0.0.1:9099", { disableWarnings: true });
const db = initializeFirestore(app, {});
connectFirestoreEmulator(db, "127.0.0.1", 8080);

const args = process.argv.slice(2);
const countArgIndex = args.indexOf("--count");
const requestedCount =
  countArgIndex >= 0 && args[countArgIndex + 1]
    ? Number.parseInt(args[countArgIndex + 1], 10)
    : 20;
const reportCount =
  Number.isFinite(requestedCount) && requestedCount > 0 ? requestedCount : 20;

// Test data generator
const damageTypes = ["pothole", "bump", "speed_bump", "roughness"];
const statuses = ["PENDING"];
const detectionSources = ["CV_ONLY", "SENSOR_ONLY", "DUAL_CONFIRMED", "MANUAL"];
const locations = [
  { lat: 41.9028, lng: 12.4964, name: "Colosseum" },
  { lat: 41.8925, lng: 12.4853, name: "Trastevere" },
  { lat: 41.9009, lng: 12.4833, name: "Piazza Navona" },
  { lat: 41.9022, lng: 12.4539, name: "Vatican" },
  { lat: 41.9109, lng: 12.4768, name: "Villa Borghese" },
  { lat: 41.8902, lng: 12.4922, name: "Circo Massimo" },
  { lat: 41.8833, lng: 12.5077, name: "Ostiense" },
  { lat: 41.9219, lng: 12.5113, name: "Nomentano" },
  { lat: 41.8897, lng: 12.5038, name: "Termini" },
  { lat: 41.9065, lng: 12.4884, name: "Trevi" },
];

function randomJitter() {
  return (Math.random() - 0.5) * 0.008;
}

function randomItem(list) {
  return list[Math.floor(Math.random() * list.length)];
}

function generateTestReports(count = 20) {
  const uid = auth.currentUser?.uid;
  if (!uid) {
    throw new Error("No authenticated user in Auth emulator");
  }

  const reports = [];
  const now = new Date();

  for (let i = 0; i < count; i++) {
    const loc = locations[i % locations.length];
    const damageType = randomItem(damageTypes);
    const status = randomItem(statuses);
    const detectionSource = randomItem(detectionSources);

    // Simulate confidence scores used by dashboard cards/details
    const cvConfidence = 0.45 + Math.random() * 0.5;
    const sensorConfidence = 0.35 + Math.random() * 0.6;
    const fusedScore = Math.min(1, cvConfidence * 0.6 + sensorConfidence * 0.4);
    const severity = Math.min(1, fusedScore * 0.85 + Math.random() * 0.15);

    const createdAt = new Date(
      now.getTime() - Math.random() * 10 * 24 * 60 * 60 * 1000,
    );
    const operatorId = "";
    const resolvedAt = null;
    const notes = "";

    reports.push({
      // Keep IDs auto-generated by Firestore addDoc
      damageType,
      severity,
      fusedScore,
      cvConfidence,
      sensorConfidence,
      status,
      detectionSource,
      location: new GeoPoint(
        loc.lat + randomJitter(),
        loc.lng + randomJitter(),
      ),
      timestamp: createdAt,
      imageUrl: "",
      userId: uid,
      operatorId,
      resolvedAt,
      notes,
    });
  }

  return reports;
}

async function seedFirestore() {
  console.log("Seeding Firestore emulator with Rome reports...\n");

  try {
    const seedEmail = "operator.release@roadguard.local";
    const seedPassword = "RoadGuard!2026";

    try {
      await createUserWithEmailAndPassword(auth, seedEmail, seedPassword);
      console.log(`Authenticated via new emulator user: ${seedEmail}`);
    } catch {
      await signInWithEmailAndPassword(auth, seedEmail, seedPassword);
      console.log(`Authenticated via existing emulator user: ${seedEmail}`);
    }

    const reports = generateTestReports(reportCount);
    const reportsRef = collection(db, "reports");

    let successCount = 0;
    for (const report of reports) {
      await addDoc(reportsRef, report);
      successCount++;
      console.log(
        `  Added ${report.damageType} (${report.status}) score=${report.fusedScore.toFixed(2)} @ ${report.location.latitude.toFixed(4)}, ${report.location.longitude.toFixed(4)}`,
      );
    }

    console.log(`\nDone. Seeded ${successCount} Rome reports.\n`);
    console.log("Reports by type:");
    const byType = {};
    reports.forEach((r) => {
      byType[r.damageType] = (byType[r.damageType] || 0) + 1;
    });
    Object.entries(byType).forEach(([type, count]) => {
      console.log(`   - ${type}: ${count}`);
    });

    console.log("\nReports by status:");
    const byStatus = {};
    reports.forEach((r) => {
      byStatus[r.status] = (byStatus[r.status] || 0) + 1;
    });
    Object.entries(byStatus).forEach(([status, count]) => {
      console.log(`   - ${status}: ${count}`);
    });

    console.log(
      "\nOpen the portal at http://127.0.0.1:4501/ to view the new Rome data.\n",
    );

    process.exit(0);
  } catch (error) {
    console.error("Error seeding Firestore:", error);
    process.exit(1);
  }
}

// Run seeding
seedFirestore();
